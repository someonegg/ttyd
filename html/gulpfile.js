const { src, dest, task, series } = require('gulp');
const clean = require('gulp-clean');
const gzip = require('gulp-gzip');
const inlineSource = require('gulp-inline-source');
const rename = require('gulp-rename');
const through2 = require('through2');
const fs = require('fs');

const genHeader = (size, buf, len) => {
    let idx = 0;
    let data = 'unsigned char index_html[] = {\n  ';

    for (const value of buf) {
        idx++;

        const current = value < 0 ? value + 256 : value;

        data += '0x';
        data += (current >>> 4).toString(16);
        data += (current & 0xf).toString(16);

        if (idx === len) {
            data += '\n';
        } else {
            data += idx % 12 === 0 ? ',\n  ' : ', ';
        }
    }

    data += '};\n';
    data += `unsigned int index_html_len = ${len};\n`;
    data += `unsigned int index_html_size = ${size};\n`;
    return data;
};
let fileSize = 0;

// Keep these resources addressable over HTTP: iOS needs an actual touch-icon URL.
task('assets', done => {
    const assets = [
        ['apple-touch-icon.png', 'image/png'],
        ['icon-192.png', 'image/png'],
        ['icon-512.png', 'image/png'],
        ['manifest.webmanifest', 'application/manifest+json'],
    ];
    let header = '/* Generated by html/gulpfile.js. */\n';
    assets.forEach(([name], i) => {
        const bytes = fs.readFileSync(`dist/${name}`);
        header += `static const unsigned char web_asset_${i}[] = {\n`;
        for (let offset = 0; offset < bytes.length; offset += 16) {
            header += `  ${Array.from(bytes.subarray(offset, offset + 16)).join(', ')},\n`;
        }
        header += '};\n';
    });
    header +=
        'static const struct {\n  const char *name;\n  const char *type;\n  const unsigned char *data;\n  size_t len;\n} web_assets[] = {\n';
    assets.forEach(([name, type], i) => {
        header += `  {"${name}", "${type}", web_asset_${i}, sizeof(web_asset_${i})},\n`;
    });
    header += '};\n';
    fs.writeFileSync('../src/web_assets.h', header);
    done();
});

task('clean', () => {
    return src('dist', { read: false, allowEmpty: true }).pipe(clean());
});

task('inline', () => {
    const options = {
        compress: false,
    };

    return src('dist/index.html').pipe(inlineSource(options)).pipe(rename('inline.html')).pipe(dest('dist/'));
});

task(
    'default',
    series('inline', 'assets', () => {
        return src('dist/inline.html')
            .pipe(
                through2.obj((file, enc, cb) => {
                    fileSize = file.contents.length;
                    return cb(null, file);
                })
            )
            .pipe(gzip())
            .pipe(
                through2.obj((file, enc, cb) => {
                    const buf = file.contents;
                    file.contents = Buffer.from(genHeader(fileSize, buf, buf.length));
                    return cb(null, file);
                })
            )
            .pipe(rename('html.h'))
            .pipe(dest('../src/'));
    })
);
